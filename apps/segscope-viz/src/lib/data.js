// ---------- E3: breaking KASLR ----------

// result-512: measurement per candidate _text offset; the real offset is the peak.
function genOffsets(seed) {
  const rng = mulberry32(seed)
  const truth = 0x1c8 // 456: the planted ground-truth offset index
  const arr = []
  for (let i = 0; i < 512; i++) {
    let v = 180 + rng() * 60
    const d = Math.abs(i - truth)
    if (d < 6) v += (6 - d) * 120 // sharp peak at the real offset
    arr.push({ offset: i, cycles: Math.round(v) })
  }
  return { truth, arr }
}
