function mulberry32(seed) {
  return function () {
    seed |= 0
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

// ---------- E1: website fingerprinting ----------

// Each site gets a distinct interrupt-count signature over the load window.
function genTrace(seed, bursts, base) {
  const rng = mulberry32(seed)
  const n = 160
  const out = []
  let level = base
  const burstAt = bursts.map((b) => Math.floor(b * n))
  for (let i = 0; i < n; i++) {
    if (burstAt.includes(i)) level += 6 + rng() * 8
    level += (rng() - 0.45) * 1.6
    if (level < base) level = base
    out.push({ t: i, irq: Math.max(0, Math.round(level + rng() * 3)) })
  }
  return out
}

